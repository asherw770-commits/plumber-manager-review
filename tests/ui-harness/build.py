#!/usr/bin/env python3
"""Builds an offline copy of the app for looking at it in a browser — Firebase is replaced by a local stub (no network, no writes).

    python3 tests/ui-harness/build.py [OUT_DIR] [DATA_JSON]

OUT_DIR   default: ./harness-out (created)
DATA_JSON the books to show, in the app's backup format. Default: fictional sample data generated by tests/sample-data.js.
Then:  cd OUT_DIR && python3 -m http.server 8775   and open  http://localhost:8775/index.html?role=admin   (or role=owner / role=manager)
"""
import os, re, shutil, subprocess, sys, time

here = os.path.dirname(os.path.abspath(__file__))
app = os.path.abspath(os.path.join(here, '..', '..'))
out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else 'harness-out')
data = sys.argv[2] if len(sys.argv) > 2 else None
os.makedirs(out, exist_ok=True)

s = open(os.path.join(app, 'index.html'), encoding='utf8').read()
i = s.index('<script type="module">'); j = s.index('</script>', i) + len('</script>')   # the Firebase module → the stub
stub = open(os.path.join(here, 'stub.js'), encoding='utf8').read()
s = s[:i] + '<script>' + stub + '</script>' + s[j:]
s = re.sub(r'ui2\.css\?v=[0-9a-z]+', 'ui2.css?t=' + str(int(time.time())), s)
s += '<script>' + open(os.path.join(here, 'dump.js'), encoding='utf8').read() + '</script>'
open(os.path.join(out, 'index.html'), 'w', encoding='utf8').write(s)
for f in os.listdir(app):
    if f.endswith(('.webp', '.png', '.jpg', '.svg', '.json')) or f == 'ui2.css':
        shutil.copy(os.path.join(app, f), os.path.join(out, f))
if data:
    shutil.copy(data, os.path.join(out, 'data.json'))
else:
    subprocess.check_call(['node', os.path.join(app, 'tests', 'sample-data.js'), os.path.join(out, 'data.json')])
print('built', len(s), '->', out)
